from __future__ import annotations

from pathlib import Path

import pandas as pd

from utils.logger import logger


class DatasetBuilder:
    """
    Builds datasets for failure prediction.

    Responsibilities:
        - Load engineered features
        - Load historical incidents
        - Merge datasets
        - Sort chronologically
        - Prepare data for label generation
    """

    def __init__(
        self,
        feature_path: str | Path,
        incident_path: str | Path,
    ) -> None:

        self.feature_path = Path(feature_path)
        self.incident_path = Path(incident_path)

    def load_features(self) -> pd.DataFrame:

        logger.info("Loading engineered features...")

        if self.feature_path.suffix == ".parquet":
            df = pd.read_parquet(self.feature_path)
        else:
            df = pd.read_csv(self.feature_path)

        logger.success(
            f"Loaded {len(df)} feature records."
        )

        return df

    def load_incidents(self) -> pd.DataFrame:

        logger.info("Loading incident history...")

        if self.incident_path.suffix == ".parquet":
            df = pd.read_parquet(self.incident_path)
        else:
            df = pd.read_csv(self.incident_path)

        logger.success(
            f"Loaded {len(df)} incidents."
        )

        return df

    def build(self) -> pd.DataFrame:
        """
        Build a unified dataset.

        The output is intentionally unlabeled.
        Labels will be generated by LabelGenerator.
        """

        features = self.load_features()

        incidents = self.load_incidents()

        if "infrastructure_asset_id" not in features.columns:
            raise ValueError(
                "Features missing infrastructure_asset_id."
            )

        if "infrastructure_asset_id" not in incidents.columns:
            raise ValueError(
                "Incidents missing infrastructure_asset_id."
            )

        dataset = features.merge(
            incidents,
            how="left",
            on="infrastructure_asset_id",
            suffixes=("", "_incident"),
        )

        timestamp_column = None

        for column in [
            "collection_timestamp",
            "timestamp",
            "created_at",
        ]:
            if column in dataset.columns:
                timestamp_column = column
                break

        if timestamp_column:

            dataset[timestamp_column] = pd.to_datetime(
                dataset[timestamp_column],
                utc=True,
            )

            dataset = dataset.sort_values(
                timestamp_column
            )

        dataset = dataset.reset_index(drop=True)

        logger.success(
            f"Unified dataset created with "
            f"{len(dataset)} rows."
        )

        return dataset

    def save(
        self,
        dataset: pd.DataFrame,
        output_path: str | Path,
    ) -> None:

        output_path = Path(output_path)

        output_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        if output_path.suffix == ".parquet":
            dataset.to_parquet(
                output_path,
                index=False,
            )
        else:
            dataset.to_csv(
                output_path,
                index=False,
            )

        logger.success(
            f"Dataset saved to {output_path}"
        )